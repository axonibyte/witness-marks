#!/usr/bin/env python3
"""Validate classified corpus entries against the extracted logs, then emit TOML.

WHY VALIDATION AND NOT TRUST. The judgment fields -- the failure class, the
state, the measurement, the fix -- are written by reading the log, and a reader
summarizing 108 incidents will eventually produce a figure that is plausible,
useful, and not in the source. That is failure class B, a lying instrument, and
building the corpus that is supposed to catalogue class B by committing one
would be a poor start.

So every NUMBER in `measurement` and `fix` must appear verbatim in that entry's
body. This does not check that the sentence is a fair summary -- no mechanical
check can -- but it does make a fabricated or miscomputed figure impossible to
commit, which is the failure that would actually mislead someone later.

usage: corpus-build.py <extracted.json> <classified.json>... -> writes TOML
"""
import json
import re
import sys
from pathlib import Path

CLASSES = set("ABCDEFG") | {""}
# a numeric token: digits, with interior dots/commas kept, surrounding junk off
NUM = re.compile(r"\d[\d.,]*")
OUT = Path("tests/corpus")


def numbers(s):
    out = set()
    for m in NUM.finditer(s):
        t = m.group(0).rstrip(".,")
        if t:
            out.add(t)
    return out


def toml_str(s):
    if "\n" in s or ('"' in s and "'" in s):
        esc = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        return f'"""\n{esc}"""'
    if '"' in s:
        return "'" + s + "'"
    return '"' + s.replace("\\", "\\\\") + '"'


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: corpus-build.py <extracted.json> <classified.json>...")
    src = {e["id"]: e for e in json.load(open(sys.argv[1], encoding="utf-8"))}
    got = []
    for p in sys.argv[2:]:
        got.extend(json.load(open(p, encoding="utf-8")))

    errs = []
    seen = {}
    for e in got:
        i = e.get("id", "<no id>")
        if i in seen:
            errs.append(f"{i}: appears more than once")
            continue
        seen[i] = e
        if i not in src:
            errs.append(f"{i}: not an id the extractor produced")
            continue
        if e.get("class", None) not in CLASSES:
            errs.append(f"{i}: class {e.get('class')!r} is not one of A-G or empty")
        for k in ("class_why", "state", "measurement", "fix"):
            if not str(e.get(k, "")).strip():
                errs.append(f"{i}: {k} is empty")
        w = len(str(e.get("class_why", "")).split())
        if w > 25:
            errs.append(f"{i}: class_why is {w} words, over the 25-word bound")
        body = src[i]["body"] + " " + src[i]["title"]
        bodynums = numbers(body)
        for field in ("measurement", "fix"):
            for n in numbers(str(e.get(field, ""))):
                if n not in bodynums:
                    errs.append(
                        f"{i}: {field} carries the number {n!r}, which is not in the log entry"
                    )
    missing = sorted(set(src) - set(seen))
    for i in missing:
        errs.append(f"{i}: extracted from the log and never classified")

    if errs:
        print(f"corpus-build: REFUSING, {len(errs)} problem(s):", file=sys.stderr)
        for e in errs[:40]:
            print("  " + e, file=sys.stderr)
        if len(errs) > 40:
            print(f"  ... and {len(errs) - 40} more", file=sys.stderr)
        sys.exit(1)

    OUT.mkdir(parents=True, exist_ok=True)
    bysrc = {}
    for i in sorted(seen):
        bysrc.setdefault(src[i]["source"], []).append(i)
    for source, ids in bysrc.items():
        lines = [
            "# GENERATED by tools/corpus-build.py. The incident logs under",
            "# /data/projects/tech/designs/ are the source of truth; this is a",
            "# structured view of them, and every number below was checked to",
            "# appear in the entry it came from.",
            "",
        ]
        for i in ids:
            e, s = seen[i], src[i]
            lines += [
                "[[incident]]",
                f'id = "{i}"',
                f'source = "{s["source"]}"',
                f'n = {s["n"]}',
                f"title = {toml_str(s['title'])}",
                f'class = "{e["class"]}"',
                f"class_why = {toml_str(e['class_why'])}",
                f"state = {toml_str(e['state'])}",
                f"measurement = {toml_str(e['measurement'])}",
                f"fix = {toml_str(e['fix'])}",
                "",
            ]
        p = OUT / f"{source}.toml"
        p.write_text("\n".join(lines), encoding="utf-8")
        print(f"wrote {p} with {len(ids)} incident(s)")
    print(f"corpus-build: {len(seen)} incident(s), every number grounded in its log entry")


if __name__ == "__main__":
    main()
